create table if not exists public.daily_metrics (
  id bigint generated by default as identity primary key,
  stat_date date not null unique,
  new_followers int,          -- Nuevos seguidores
  new_conversations int,      -- Nuevas conversaciones
  follow_ups int,             -- Follow ups
  proposals int,              -- Propuesta de agenda
  calls_scheduled int,        -- Llamadas agendadas
  sales_closed int,           -- Ventas cerradas
  ticket numeric(12,2),       -- Ticket (valor de cada venta)
  notes text,
  updated_at timestamptz not null default now()
);

alter table public.daily_metrics enable row level security;
drop policy if exists "equipo_lee" on public.daily_metrics;
create policy "equipo_lee" on public.daily_metrics for select to authenticated using (true);
drop policy if exists "equipo_escribe" on public.daily_metrics;
create policy "equipo_escribe" on public.daily_metrics for all to authenticated using (true) with check (true);

-- Crea las filas que falten para todos los días de un mes (ej: '2026-08-01')
create or replace function public.ensure_month_rows(p_month date)
returns void language sql security invoker set search_path = public as $$
  insert into public.daily_metrics (stat_date)
  select d::date
  from generate_series(date_trunc('month', p_month), date_trunc('month', p_month) + interval '1 month - 1 day', interval '1 day') d
  on conflict (stat_date) do nothing;
$$;
grant execute on function public.ensure_month_rows(date) to authenticated;
