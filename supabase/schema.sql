-- ---------- Usuarios del sistema (perfil de cada login) ----------
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text,
  email text,
  role text not null default 'usuario' check (role in ('admin','usuario')),
  active boolean not null default true,
  created_at timestamptz not null default now()
);

-- El alta de usuarios, el superusuario inicial y los permisos de perfiles
-- están en 02_usuarios.sql (ejecutarlo después de este archivo).

-- ---------- Planes ----------
create table if not exists public.plans (
  id bigint generated by default as identity primary key,
  name text not null default 'Nuevo plan',
  price numeric(12,2) default 0,
  description text,
  active boolean not null default true,
  created_at timestamptz not null default now()
);

-- ---------- Estados de llamadas (configurables) ----------
create table if not exists public.call_statuses (
  id bigint generated by default as identity primary key,
  name text not null default 'Nuevo estado',
  color text not null default '#64748b',
  sort_order int not null default 0,
  is_final boolean not null default false,   -- la llamada ya terminó (concretada, cerrada, perdida...)
  is_won boolean not null default false,     -- cuenta como venta / cierre exitoso
  active boolean not null default true
);

-- ---------- Estados de clientes (configurables) ----------
create table if not exists public.client_statuses (
  id bigint generated by default as identity primary key,
  name text not null default 'Nuevo estado',
  color text not null default '#64748b',
  sort_order int not null default 0,
  active boolean not null default true
);

-- ---------- Campos personalizados (columnas extra que crea el usuario) ----------
create table if not exists public.custom_fields (
  id bigint generated by default as identity primary key,
  entity text not null default 'clients' check (entity in ('clients','calls')),
  label text not null default 'Nuevo campo',
  field_key text not null default ('campo_' || substr(md5(random()::text), 1, 6)),
  field_type text not null default 'texto' check (field_type in ('texto','numero','fecha','lista','si_no')),
  options text,           -- para tipo "lista": opciones separadas por coma
  sort_order int not null default 0,
  active boolean not null default true,
  unique (entity, field_key)
);

-- ---------- Clientes ----------
create table if not exists public.clients (
  id bigint generated by default as identity primary key,
  name text not null default '',
  company text,
  phone text,
  email text,
  plan_id bigint references public.plans(id) on delete set null,
  owner_id uuid references public.profiles(id) on delete set null,
  status_id bigint references public.client_statuses(id) on delete set null,
  source text,
  notes text,
  custom jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

-- ---------- Llamadas ----------
create table if not exists public.calls (
  id bigint generated by default as identity primary key,
  client_id bigint references public.clients(id) on delete cascade,
  user_id uuid references public.profiles(id) on delete set null,
  status_id bigint references public.call_statuses(id) on delete set null,
  scheduled_date date default current_date,
  scheduled_time text,
  duration_min int,
  result text,
  notes text,
  custom jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

-- ---------- Redes sociales ----------
create table if not exists public.social_accounts (
  id bigint generated by default as identity primary key,
  network text not null default 'Instagram',
  handle text not null default '@cuenta',
  color text not null default '#6366f1',
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.social_stats (
  id bigint generated by default as identity primary key,
  account_id bigint references public.social_accounts(id) on delete cascade,
  stat_date date not null default current_date,
  followers int,
  conversations int,
  messages int,
  posts int,
  reach int,
  notes text,
  created_at timestamptz not null default now()
);

create index if not exists calls_client_idx on public.calls(client_id);
create index if not exists calls_date_idx on public.calls(scheduled_date);
create index if not exists clients_owner_idx on public.clients(owner_id);
create index if not exists social_stats_idx on public.social_stats(account_id, stat_date);

-- ---------- Seguridad: solo usuarios con sesión iniciada ----------
do $$
declare t text;
begin
  foreach t in array array['profiles','plans','call_statuses','client_statuses','custom_fields',
                           'clients','calls','social_accounts','social_stats']
  loop
    execute format('alter table public.%I enable row level security', t);
    execute format('drop policy if exists "equipo_lee" on public.%I', t);
    execute format('create policy "equipo_lee" on public.%I for select to authenticated using (true)', t);
    if t <> 'profiles' then
      execute format('drop policy if exists "equipo_escribe" on public.%I', t);
      execute format('create policy "equipo_escribe" on public.%I for all to authenticated using (true) with check (true)', t);
    end if;
  end loop;
end $$;

