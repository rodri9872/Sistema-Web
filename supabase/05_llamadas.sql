-- Columnas nuevas de llamadas
alter table public.calls add column if not exists scheduled_on date default current_date; -- Fecha en que se agendó
alter table public.calls add column if not exists setter_id uuid references public.profiles(id) on delete set null; -- Quién la agendó
alter table public.calls add column if not exists contact_name text;   -- Nombre
alter table public.calls add column if not exists country text;        -- País
alter table public.calls add column if not exists channel text;        -- Vía (IG, WhatsApp...)
alter table public.calls add column if not exists completed boolean;   -- Realizada (Sí / No)
alter table public.calls add column if not exists close_result text;   -- Cierre
alter table public.calls add column if not exists payment_type text;   -- Tipo de pago

update public.calls set scheduled_on = coalesce(scheduled_on, created_at::date) where scheduled_on is null;

-- Listas desplegables configurables
create table if not exists public.option_lists (
  id bigint generated by default as identity primary key,
  list_key text not null default 'via' check (list_key in ('via', 'cierre', 'tipo_pago')),
  value text not null default 'Nueva opción',
  color text not null default '#64748b',
  sort_order int not null default 0,
  is_won boolean not null default false,  -- para "Cierre": cuenta como venta
  active boolean not null default true
);

alter table public.option_lists enable row level security;
drop policy if exists "equipo_lee" on public.option_lists;
create policy "equipo_lee" on public.option_lists for select to authenticated using (true);
drop policy if exists "equipo_escribe" on public.option_lists;
create policy "equipo_escribe" on public.option_lists for all to authenticated using (true) with check (true);
grant select, insert, update, delete on public.option_lists to authenticated;
grant usage, select on all sequences in schema public to authenticated;

